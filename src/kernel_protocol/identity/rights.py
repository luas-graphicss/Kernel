RIGHT_SEND = 0x01
RIGHT_RECEIVE = 0x02
RIGHT_READ = 0x04
RIGHT_WRITE = 0x08
RIGHT_MAP = 0x10
RIGHT_DELEGATE = 0x20
RIGHT_ADMIN = 0x40
RIGHTS_ALL = 0x7F

OBJECT_NONE = 0
OBJECT_SYSTEM = 1
OBJECT_PROCESS = 2
OBJECT_ENDPOINT = 3
OBJECT_BUFFER = 4
OBJECT_REPLY = 5

CAPABILITY_MAX_DEPTH = 16

INSPECT_KIND_MASK = 0xFF
INSPECT_RIGHTS_SHIFT = 8
INSPECT_DEPTH_SHIFT = 16


def unpack_inspection(value: int) -> tuple[int, int, int]:
    kind = value & INSPECT_KIND_MASK
    rights = (value >> INSPECT_RIGHTS_SHIFT) & RIGHTS_ALL
    return kind, rights, value >> INSPECT_DEPTH_SHIFT
