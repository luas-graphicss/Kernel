#ifndef KERNEL_DEVICES_VIRTIO_MMIO_H
#define KERNEL_DEVICES_VIRTIO_MMIO_H

#include <stdint.h>

#define VIRTIO_MMIO_MAGIC 0x74726976u
#define VIRTIO_MMIO_VERSION 2u
#define VIRTIO_MMIO_REGISTER_BYTES 0x200u

#define VIRTIO_MMIO_MAGIC_VALUE 0x000u
#define VIRTIO_MMIO_VERSION_VALUE 0x004u
#define VIRTIO_MMIO_DEVICE_ID 0x008u
#define VIRTIO_MMIO_DEVICE_FEATURES 0x010u
#define VIRTIO_MMIO_DEVICE_FEATURES_SELECT 0x014u
#define VIRTIO_MMIO_DRIVER_FEATURES 0x020u
#define VIRTIO_MMIO_DRIVER_FEATURES_SELECT 0x024u
#define VIRTIO_MMIO_QUEUE_SELECT 0x030u
#define VIRTIO_MMIO_QUEUE_SIZE_MAX 0x034u
#define VIRTIO_MMIO_QUEUE_SIZE 0x038u
#define VIRTIO_MMIO_QUEUE_READY 0x044u
#define VIRTIO_MMIO_QUEUE_NOTIFY 0x050u
#define VIRTIO_MMIO_INTERRUPT_STATUS 0x060u
#define VIRTIO_MMIO_INTERRUPT_ACKNOWLEDGE 0x064u
#define VIRTIO_MMIO_STATUS 0x070u
#define VIRTIO_MMIO_QUEUE_DESCRIPTOR_LOW 0x080u
#define VIRTIO_MMIO_QUEUE_DESCRIPTOR_HIGH 0x084u
#define VIRTIO_MMIO_QUEUE_DRIVER_LOW 0x090u
#define VIRTIO_MMIO_QUEUE_DRIVER_HIGH 0x094u
#define VIRTIO_MMIO_QUEUE_DEVICE_LOW 0x0a0u
#define VIRTIO_MMIO_QUEUE_DEVICE_HIGH 0x0a4u
#define VIRTIO_MMIO_CONFIG_GENERATION 0x0fcu
#define VIRTIO_MMIO_CONFIG 0x100u

#define VIRTIO_STATUS_ACKNOWLEDGE 0x01u
#define VIRTIO_STATUS_DRIVER 0x02u
#define VIRTIO_STATUS_DRIVER_OK 0x04u
#define VIRTIO_STATUS_FEATURES_OK 0x08u
#define VIRTIO_STATUS_NEEDS_RESET 0x40u
#define VIRTIO_STATUS_FAILED 0x80u

#define VIRTIO_FEATURE_VERSION_1 (1ull << 32)

uint32_t virtio_mmio_read(uintptr_t device, uint32_t offset);
void virtio_mmio_write(uintptr_t device, uint32_t offset, uint32_t value);
uint8_t virtio_mmio_read_config(uintptr_t device, uint32_t offset);

#endif
